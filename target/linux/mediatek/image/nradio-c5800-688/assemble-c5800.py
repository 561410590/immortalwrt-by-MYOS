def run(*args):
    subprocess.run([str(a) for a in args], check=True)

def copy(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)

def write(relative, value, mode=0o644):
    path = work / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        path.unlink()
    path.write_text(value)
    path.chmod(mode)

def set_proxy_defaults(name, section, options):
    relative = 'etc/config/' + name
    text = (work / relative).read_text()
    pattern = r'(?ms)^(config[ \t]+' + re.escape(section) + r'(?:[ \t]+[^\n]*)?\n)(.*?)(?=^config[ \t]|\Z)'
    def update(match):
        body = match[2]
        for key, value in options.items():
            body = re.sub(r'(?m)^[ \t]*option[ \t]+' + re.escape(key) + r'[ \t]+[^\n]*(?:\n|$)', '', body)
            if value is not None:
                body = "\toption " + key + " '" + str(value) + "'\n" + body
        return match[1] + body
    write(relative, re.sub(pattern, update, text, count=1))

def link(relative, target):
    path = work / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink() or path.exists():
        path.unlink()
    path.symlink_to(target)

def extract_checked(archive, destination):
    for item in archive.getmembers():
        name = item.name.removeprefix('./')
        if name.startswith('/') or '..' in Path(name).parts:
            raise RuntimeError('Unsafe package member: ' + name)
    archive.extractall(destination)

def package(path, include_data=True):
    with tarfile.open(path, 'r:*') as outer:
        members = {Path(m.name).name: m for m in outer.getmembers()}
        control_name = next(n for n in members if n.startswith('control.tar'))
        data_name = next(n for n in members if n.startswith('data.tar'))
        control = tarfile.open(fileobj=io.BytesIO(outer.extractfile(members[control_name]).read()), mode='r:*')
        data = outer.extractfile(members[data_name]).read() if include_data else None
        content = {Path(m.name).name: (control.extractfile(m).read(), m.mode)
                   for m in control.getmembers() if m.isfile()}
    record = content['control'][0].decode()
    name = re.search(r'^Package: (.+)$', record, re.M)[1]
    return name, record, content, data

